"""Regenerate the embedded switch artwork (development only; requires Pillow)."""
import base64
import io
from pathlib import Path
from PIL import Image, ImageDraw

SCALE = 8
COLORS = {'off': '#414B58', 'orange': '#FF8A4C', 'blue': '#7DB4FF'}
images = {}
for state, color in COLORS.items():
    for focused in (False, True):
        image = Image.new('RGBA', (46*SCALE, 28*SCALE))
        draw = ImageDraw.Draw(image)
        def box(values):
            return tuple(round(value*SCALE) for value in values)
        if focused:
            draw.rounded_rectangle(box((.5, .5, 45.5, 27.5)), radius=13.5*SCALE, fill='#F2F4F7')
        draw.rounded_rectangle(box((1.5, 2, 44.5, 26)), radius=12*SCALE, fill=color)
        center = 13.5 if state == 'off' else 32.5
        draw.ellipse(box((center-9, 5, center+9, 23)), fill='#DDE3EA' if state == 'off' else '#FFFFFF')
        image = image.resize((46, 28), Image.Resampling.LANCZOS)
        data = io.BytesIO()
        image.save(data, format='PNG', optimize=True)
        images[state + ('_focus' if focused else '')] = base64.b64encode(data.getvalue()).decode('ascii')
output = Path(__file__).resolve().parents[1] / 'switch_art.py'
output.write_text('"""Antialiased switch artwork. Generated by tools/generate_switch_art.py."""\n\nSWITCH_IMAGES = ' + repr(images) + '\n', encoding='utf-8')
